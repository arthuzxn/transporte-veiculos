CREATE TABLE TB_EQUIPAMENTO
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    placaCavalo VARCHAR(7) NOT NULL,
    placaCarreta VARCHAR(7) NOT NULL,
    modeloCavalo VARCHAR(255) NOT NULL,
    modeloCarreta VARCHAR(255) NOT NULL,
    transportadora_id BIGINT NOT NULL,
    PRIMARY KEY(id)
);

CREATE TABLE TB_TRANSPORTADORA
(
    id BIGINT  GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR(255) NOT NULL,
    cnpj VARCHAR(14) NOT NULL,
    PRIMARY KEY(id)
);

CREATE TABLE TB_MOTORISTA
(
    id BIGINT  GENERATED BY DEFAULT AS IDENTITY,
    cpf VARCHAR(11) NOT NULL,
    nome VARCHAR(255) NOT NULL,
    dataNascimento DATE NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    transportadora_id BIGINT NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE TB_ENDERECO
(
    id BIGINT  GENERATED BY DEFAULT AS IDENTITY,
    cep VARCHAR(8) NOT NULL,
    logradouro varchar(255) NOT NULL,
    numero smallint NOT NULL,
    complemento VARCHAR(255),
    bairro VARCHAR(255) NOT NULL,
    cidade VARCHAR(255) NOT NULL,
    estado VARCHAR(255) NOT NULL,
    pais VARCHAR(255) DEFAULT 'Brasil' NOT NULL,
    primary key (id)
);

CREATE TABLE TB_FILIAL(
    id BIGINT  GENERATED BY DEFAULT AS IDENTITY,
    apelido VARCHAR(255) NOT NULL,
    codigoFilial VARCHAR(50) NOT NULL,
    endereco_id BIGINT NOT NULL UNIQUE,
    primary key (id)
);

CREATE TABLE TB_DEALER(

    id BIGINT  GENERATED BY DEFAULT AS IDENTITY,
    codigo_dealer VARCHAR(50) NOT NULL,
    nome VARCHAR(255) NOT NULL,
    endereco_id BIGINT NOT NULL UNIQUE,
    PRIMARY KEY (id)
);

CREATE TABLE TB_VEICULO
(
    id BIGINT  GENERATED BY DEFAULT AS IDENTITY,
    chassi VARCHAR(17) NOT NULL,
    modelo VARCHAR(255) NOT NULL,
    marca ENUM('GENERAL_MOTORS','VOLKSWAGEN','BYD','RENAULT','FIAT', 'NISSAN','TOYOTA','PEUGEOT','CITROEN') NOT NULL,
    status ENUM ('ESTOQUE', 'EMBARCADO', 'ENTREGUE') DEFAULT 'ESTOQUE' NOT NULL,
    viagem_id BIGINT NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE TB_OCORRENCIA
(
    id BIGINT  GENERATED BY DEFAULT AS IDENTITY,
    descricao VARCHAR(255) NOT NULL,
    veiculo_id BIGINT NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE TB_VIAGEM
(
    id BIGINT  GENERATED BY DEFAULT AS IDENTITY,
    motorista_id BIGINT NOT NULL,
    equipamento_id BIGINT NOT NULL,
    numero_viagem BIGINT NOT NULL,
    filial_id BIGINT NOT NULL,
    momento_emissao DATETIME NOT NULL,
    data_prevista_entrega DATE NOT NULL,
    data_entrega DATETIME,
    PRIMARY KEY (id)
);

CREATE TABLE TB_VIAGEM_DEALER
(
    id_viagem BIGINT NOT NULL,
    id_dealer BIGINT NOT NULL,
    PRIMARY KEY (id_viagem, id_dealer)
);


